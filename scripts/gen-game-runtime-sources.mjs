#!/usr/bin/env node
// Embed the bwgame-v1 runtime files as strings so the exporter works in the
// browser (no file access) as well as in Node. Regenerate after editing any file
// in src/game/runtime/; test/game-export.test.mjs fails if this is stale.
//
//   node scripts/gen-game-runtime-sources.mjs          write
//   node scripts/gen-game-runtime-sources.mjs --check  exit 1 if stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'game', 'runtime');
const FILES = ['bwgame.js', 'bwgame-web.js', 'bwgame.py'];
const allowMissing = process.argv.includes('--allow-missing');

export function render () {
    const entries = FILES.map((f) => {
        const p = path.join(dir, f);
        if (!existsSync(p)) {
            if (!allowMissing) throw new Error(`missing ${p}`);
            return [f, ''];
        }
        return [f, readFileSync(p, 'utf8')];
    });
    return [
        '// GENERATED by scripts/gen-game-runtime-sources.mjs — do not edit by hand.',
        '// The bwgame-v1 runtime sources, embedded for the game exporter.',
        'export const RUNTIME_SOURCES = {',
        ...entries.map(([f, s]) => `    ${JSON.stringify(f)}: ${JSON.stringify(s)},`),
        '};',
        ''
    ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
    const out = path.join(dir, 'sources.generated.js');
    const text = render();
    if (process.argv.includes('--check')) {
        const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
        if (cur !== text) { console.error('sources.generated.js is stale: run node scripts/gen-game-runtime-sources.mjs'); process.exit(1); }
        console.log('sources.generated.js is current');
    } else {
        writeFileSync(out, text);
        console.log(`wrote ${path.relative(process.cwd(), out)}`);
    }
}
