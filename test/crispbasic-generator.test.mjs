import test from 'node:test';
import assert from 'node:assert/strict';
import SB3Creator from '../src/utils/sb3Creator.js';

const options = {profile: 'bbc', mode: 'crispbasic', lineNumbers: false};
const build = source => {
    const creator = new SB3Creator();
    creator.parse(source);
    return creator;
};
const pinSource = body => `DEVICE ARDUINO-UNO\nPIN led = D13 OUTPUT ACTIVE LOW\nPIN button = D2 INPUT ACTIVE LOW\nWHEN flag clicked:\n${body}\n`;
const blockOf = (creator, opcode) => {
    for (const target of creator.project.targets) {
        for (const [id, block] of Object.entries(target.blocks)) {
            if (block.opcode === opcode) return {id, block, blocks: target.blocks};
        }
    }
    assert.fail(`fixture has ${opcode}`);
};
const generate = source => build(source).generateBASIC(undefined, options);
const accepted = result => {
    assert.equal(result.ok, true, JSON.stringify(result));
    assert.deepEqual(result.reasons, []);
    assert.deepEqual(result.diagnostics, []);
    assert.equal(result.mode, 'crispbasic');
    return result.basic;
};
const declined = (result, code) => {
    assert.equal(result.ok, false, JSON.stringify(result));
    assert.equal(Object.hasOwn(result, 'basic'), false, 'a refused program has no executable partial source');
    assert.ok(result.diagnostics.some(d => d.code === `crispbasic-${code}`), JSON.stringify(result));
    assert.ok(result.reasons.length);
};

test('portable generation is explicit; default and explicit legacy BBC output retain their bytes', () => {
    const creator = build('WHEN flag clicked:\n  say "hi"\n  wait 0.25 seconds');
    const legacy = creator.generateBASIC(undefined, {profile: 'bbc', lineNumbers: false});
    assert.equal(legacy.basic, 'REM generated by Brickwright (BBC BASIC profile)\nPRINT "hi"\ntime_target=TIME+0.25*100\nREPEAT UNTIL TIME>=time_target\nEND\n');
    assert.deepEqual(creator.generateBASIC(undefined, {profile: 'bbc', lineNumbers: false, mode: 'legacy'}), legacy);
    const portable = accepted(creator.generateBASIC(undefined, options));
    assert.match(portable, /^PROCdelay\(250\)$/m);
    assert.doesNotMatch(portable, /time_target|\bTIME\b/);
});

test('legacy VIA and non-VIA hardware behavior remain unchanged', () => {
    const eater = build('DEVICE EATER6502\nPIN led = PA0 OUTPUT\nWHEN flag clicked:\n  turn on led\n  wait 0.25 seconds\n  toggle led');
    assert.equal(eater.generateBASIC(undefined, {lineNumbers: false}).basic,
        'REM generated by Brickwright (BBC BASIC profile)\nREM @bw device eater6502\nREM @bw pin led PA0 output\n?&6003=1\n?&6001=?&6001 OR 1\ntime_target=TIME+0.25*100\nREPEAT UNTIL TIME>=time_target\n?&6001=?&6001 EOR 1\nEND\n');
    const uno = build(pinSource('  turn on led\n  toggle led'));
    const result = uno.generateBASIC(undefined, {lineNumbers: false});
    assert.equal(result.ok, true);
    assert.match(result.basic, /^REM turn on led\nREM toggle led$/m);
    assert.doesNotMatch(result.basic, /PROCdigitalWrite|FNdigitalRead/);
    assert.match(result.warnings.join('\n'), /REM stubs/);
});

test('non-BBC and unknown portable modes are refused', () => {
    const creator = build('WHEN flag clicked:\n  say "hi"');
    declined(creator.generateBASIC(undefined, {...options, profile: 'ms'}), 'profile');
    declined(creator.generateBASIC(undefined, {...options, mode: 'crispbasik'}), 'mode');
});

for (const [device, where, expected] of [
    ['ARDUINO-UNO', 'D13', 13], ['ARDUINO-UNO', 'A5', 19],
    ['ARDUINO-NANO', 'A0', 14], ['ARDUINO-MEGA', 'D53', 53], ['ARDUINO-MEGA', 'A15', 69],
    ['PICO', 'GP22', 22], ['PICO', 'GP25', 25], ['PICO', 'GP28', 28],
    ['STC12C5A60S2', 'P1.0', 8], ['STC15F2K60S2', 'P3.7', 31]
]) {
    test(`${device} ${where} maps deliberately to logical pin ${expected}`, () => {
        const code = accepted(generate(`DEVICE ${device}\nPIN led = ${where} OUTPUT\nWHEN flag clicked:\n  turn on led`));
        assert.match(code, new RegExp(`^PROCpinMode\\(${expected},"output"\\)$`, 'm'));
        assert.match(code, new RegExp(`^PROCdigitalWrite\\(${expected},1\\)$`, 'm'));
        assert.doesNotMatch(code, /\?&|\bPOKE\b|REM turn/);
    });
}

test('active-low logical actions and reads differ from explicit electrical levels', () => {
    const code = accepted(generate(pinSource('  turn on led\n  turn off led\n  set led high\n  set led low\n  set led to read button')));
    assert.match(code, /^PROCpinMode\(2,"input-pullup"\)$/m);
    assert.match(code, /PROCdigitalWrite\(13,0\)\nPROCdigitalWrite\(13,1\)\nPROCdigitalWrite\(13,1\)\nPROCdigitalWrite\(13,0\)/);
    assert.match(code, /^PROCdigitalWrite\(13,ABS\(\(\(1-FNdigitalRead\(2\)\)\)<>0\)\)$/m);
    assert.equal((code.match(/FNdigitalRead/g) || []).length, 1, 'the read is evaluated once');
});

test('active-high input is released input; numeric levels become exact 0/1 expressions', () => {
    const code = accepted(generate('DEVICE ARDUINO-UNO\nPIN led = D13 OUTPUT\nPIN button = D2 INPUT\nWHEN flag clicked:\n  set led to -7\n  set led to 0\n  set led to 0.25\n  print read button'));
    assert.match(code, /^PROCpinMode\(2,"input"\)$/m);
    assert.match(code, /^PROCdigitalWrite\(13,ABS\(\(-7\)<>0\)\)$/m);
    assert.match(code, /^PROCdigitalWrite\(13,ABS\(\(0\)<>0\)\)$/m);
    assert.match(code, /^PROCdigitalWrite\(13,ABS\(\(0\.25\)<>0\)\)$/m);
    assert.match(code, /^PRINT FNdigitalRead\(2\)$/m);
});

test('a native Scratch Boolean connected to a digital write is grouped and normalized', () => {
    const creator = build(pinSource('  set led to 0'));
    const {id, block, blocks} = blockOf(creator, 'stc12_writepin');
    block.inputs.VALUE = [2, 'comparison'];
    blocks.comparison = {opcode: 'operator_gt', parent: id, next: null, shadow: false, topLevel: false,
        fields: {}, inputs: {OPERAND1: [1, [4, '2']], OPERAND2: [1, [4, '1']]}};
    const code = accepted(creator.generateBASIC(undefined, options));
    assert.ok(code.includes('PROCdigitalWrite(13,ABS((ABS((2)>(1)))<>0))'), code);
});

for (const [opcode, inputs, expression] of [
    ['operator_not', {OPERAND: [1, [4, '1']]}, 'ABS((1)=0)'],
    ['operator_and', {OPERAND1: [1, [4, '1']], OPERAND2: [1, [4, '2']]}, 'ABS(((1)<>0) AND ((2)<>0))'],
    ['operator_or', {OPERAND1: [1, [4, '0']], OPERAND2: [1, [4, '2']]}, 'ABS(((0)<>0) OR ((2)<>0))'],
    ['planetemaths_not', {A: [1, [4, '1']]}, 'ABS((1)=0)'],
    ['planetemaths_and', {A: [1, [4, '1']], B: [1, [4, '2']]}, 'ABS(((1)<>0) AND ((2)<>0))']
]) {
    test(`${opcode} normalizes truth values before BBC bitwise Boolean operations`, () => {
        const creator = build(pinSource('  set led to 0'));
        const {id, block, blocks} = blockOf(creator, 'stc12_writepin');
        block.inputs.VALUE = [2, 'truth'];
        blocks.truth = {opcode, parent: id, next: null, shadow: false, topLevel: false, fields: {}, inputs};
        const code = accepted(creator.generateBASIC(undefined, options));
        assert.ok(code.includes(`PROCdigitalWrite(13,ABS((${expression})<>0))`), code);
    });
}

test('Boolean reporters retain 0/1 values and precedence inside arithmetic', () => {
    const creator = build(pinSource('  set led to 0'));
    const {id, block, blocks} = blockOf(creator, 'stc12_writepin');
    block.inputs.VALUE = [2, 'sum'];
    blocks.sum = {opcode: 'operator_add', parent: id, next: null, shadow: false, topLevel: false,
        fields: {}, inputs: {NUM1: [2, 'predicate'], NUM2: [1, [4, '-1']]}};
    blocks.predicate = {opcode: 'operator_gt', parent: 'sum', next: null, shadow: false, topLevel: false,
        fields: {}, inputs: {OPERAND1: [1, [4, '2']], OPERAND2: [1, [4, '1']]}};
    const code = accepted(creator.generateBASIC(undefined, options));
    assert.ok(code.includes('PROCdigitalWrite(13,ABS(((ABS((2)>(1))+-1))<>0))'), code);
});

test('the VM-persisted hardware metadata is read without relying on decompile side effects', () => {
    const creator = build(pinSource('  turn on led\n  wait 0.025 seconds'));
    SB3Creator.writeStcComment(creator.project);
    const saved = JSON.parse(JSON.stringify(creator.project));
    delete saved.stc;
    const original = JSON.stringify(saved);
    const code = accepted(creator.generateBASIC(saved, options));
    assert.match(code, /^PROCpinMode\(13,"output"\)$/m);
    assert.match(code, /^PROCdigitalWrite\(13,0\)$/m);
    assert.equal(JSON.stringify(saved), original, 'generation does not mutate the saved project');
    saved.boards = [{name: 'one', targets: [], stc: creator.project.stc}, {name: 'two', targets: [], stc: creator.project.stc}];
    declined(creator.generateBASIC(saved, options), 'multiple-boards');
});

