test('unsupported device, pin location, mode, aliases and write direction are clear refusals', () => {
    declined(generate('DEVICE MICROBIT\nPIN led = P0 OUTPUT\nWHEN flag clicked:\n  turn on led'), 'device');
    for (const [device, where] of [['PICO', 'GP23'], ['PICO', 'GP24']]) {
        declined(generate(`DEVICE ${device}\nPIN led = ${where} OUTPUT\nWHEN flag clicked:\n  turn on led`), 'pin-map');
    }
    for (const mode of ['analog', 'pwm', 'tone', 'input-pulldown']) {
        const creator = build(pinSource('  turn on led'));
        creator.project.stc.pins[0].direction = mode;
        declined(creator.generateBASIC(undefined, options), 'pin-mode');
    }
    const nano = build(pinSource('  turn on led'));
    nano.project.stc.device = 'arduino-nano'; nano.project.stc.pins[0].where = 'A6';
    declined(nano.generateBASIC(undefined, options), 'pin-map');
    const aliases = build(pinSource('  turn on led'));
    aliases.project.stc.pins[1].where = 'D13';
    declined(aliases.generateBASIC(undefined, options), 'pin-alias');
    declined(generate(pinSource('  set button high')), 'pin-not-output');
    const undeclared = build(pinSource('  turn on led'));
    blockOf(undeclared, 'stc12_setpin').block.fields.PIN[0] = 'missing';
    declined(undeclared.generateBASIC(undefined, options), 'undeclared-pin');
});

test('unsupported hardware statements, reporters and declarations cannot become executable comments', () => {
    declined(generate('DEVICE ARDUINO-UNO\nPIN lamp = D3 PWM\nWHEN flag clicked:\n  set lamp to 50 percent'), 'pin-mode');
    const port = build(pinSource('  turn on led'));
    port.project.stc.ports.push({name: 'bus', port: 1, direction: 'output'});
    declined(port.generateBASIC(undefined, options), 'port');
    const part = build(pinSource('  turn on led'));
    part.project.stc.parts.push({name: 'screen', type: 'oled'});
    declined(part.generateBASIC(undefined, options), 'peripheral');
    const unsupported = build(pinSource('  turn on led'));
    blockOf(unsupported, 'stc12_setpin').block.opcode = 'stc12_settone';
    declined(unsupported.generateBASIC(undefined, options), 'operation');
    const reporter = build(pinSource('  print read button'));
    const {id, block} = blockOf(reporter, 'stc12_read'); block.opcode = 'devices_temperature';
    const result = reporter.generateBASIC(undefined, options);
    declined(result, 'reporter');
    assert.equal(result.diagnostics[0].blockId, id);
    declined(generate(pinSource('  set led to "high"')), 'numeric-value');
});

