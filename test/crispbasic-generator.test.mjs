test('seconds round to nearest integer milliseconds, including zero and half-millisecond ties', () => {
    const code = accepted(generate('WHEN flag clicked:\n  wait 0 seconds\n  wait 0.0004 seconds\n  wait 0.0005 seconds\n  wait 0.0015 seconds\n  wait 0.025 seconds\n  wait 2147483.647 seconds'));
    assert.deepEqual([...code.matchAll(/^PROCdelay\((\d+)\)$/gm)].map(m => Number(m[1])), [0, 0, 1, 2, 25, 2147483647]);
});

for (const value of ['-0.001', '2147483.648', '1e309', '"later"']) {
    test(`invalid literal delay ${value} is a named source-block refusal`, () => {
        const creator = build(`WHEN flag clicked:\n  wait ${value} seconds`);
        const {id} = blockOf(creator, 'control_wait');
        const result = creator.generateBASIC(undefined, options);
        declined(result, 'delay-range');
        assert.equal(result.diagnostics[0].blockId, id);
        assert.equal(result.diagnostics[0].opcode, 'control_wait');
    });
}

test('computed delay evaluates the reporter once and maps all validation lines to its block', () => {
    const creator = build(pinSource('  wait read button seconds'));
    const {id} = blockOf(creator, 'control_wait');
    const result = creator.generateBASIC(undefined, options);
    const code = accepted(result);
    assert.equal((code.match(/FNdigitalRead/g) || []).length, 1);
    assert.match(code, /^_bw_crisp_seconds=\(1-FNdigitalRead\(2\)\)$/m);
    assert.match(code, /^IF _bw_crisp_seconds<0 OR _bw_crisp_seconds>2147483\.647 THEN ERROR 204,/m);
    assert.match(code, /^PROCdelay\(INT\(_bw_crisp_seconds\*1000\+0\.5\)\)$/m);
    assert.equal(Object.values(result.lineMap).filter(value => value === id).length, 3);
});

test('all supported timed statement forms use the same millisecond conversion', () => {
    const code = accepted(generate('WHEN flag clicked:\n  say "say" for 0.0015 seconds\n  think "think" for 0.025 seconds\n  glide 0.5 secs to x: 0 y: 0'));
    assert.deepEqual([...code.matchAll(/^PROCdelay\((\d+)\)$/gm)].map(m => Number(m[1])), [2, 25, 500]);
    assert.doesNotMatch(code, /\bTIME\b|time_target/);
});

test('timer reset moves an offset without resetting simulated time; internal names cannot collide', () => {
    const code = accepted(generate('WHEN flag clicked:\n  set _bw_crisp_seconds to 0.25\n  set _bw_crisp_timer_base to 7\n  wait _bw_crisp_seconds seconds\n  reset timer\n  print timer\n  print _bw_crisp_timer_base'));
    assert.match(code, /^_bw_crisp_secondsx=0\.25$/m);
    assert.match(code, /^_bw_crisp_seconds=_bw_crisp_secondsx$/m);
    assert.match(code, /^_bw_crisp_timer_basex=7$/m);
    assert.equal((code.match(/^_bw_crisp_timer_base=FNmillis$/gm) || []).length, 2, 'initial origin and reset');
    assert.match(code, /^PRINT \(\(FNmillis-_bw_crisp_timer_base\)\/1000\)$/m);
    assert.match(code, /^PRINT _bw_crisp_timer_basex$/m);
    assert.doesNotMatch(code, /\bTIME\b/);
});

test('referenced scalar initial values are preserved for computed levels and delays', () => {
    const creator = build(pinSource('  set led to stored\n  wait duration seconds'));
    for (const target of creator.project.targets) {
        for (const variable of Object.values(target.variables)) {
            if (variable[0] === 'stored') variable[1] = -7;
            if (variable[0] === 'duration') variable[1] = '0.025';
        }
        target.variables.unused = ['unused text', 'must not affect numeric generation'];
    }
    const result = creator.generateBASIC(undefined, options);
    const code = accepted(result);
    assert.match(code, /^stored=-7$/m);
    assert.match(code, /^duration=0\.025$/m);
    assert.ok(code.indexOf('stored=-7') < code.indexOf('PROCdigitalWrite'));
    assert.ok(code.indexOf('duration=0.025') < code.indexOf('_bw_crisp_seconds=duration'));
    for (const [index, line] of code.split('\n').entries()) {
        if (line === 'stored=-7' || line === 'duration=0.025') assert.equal(result.lineMap[index + 1], undefined);
    }
    assert.doesNotMatch(code, /unused text/);
});

test('unrepresentable, missing or ambiguous scalar initial values are explicit refusals', () => {
    for (const value of ['high', '', null, Infinity, {value: 1}]) {
        const creator = build(pinSource('  set led to stored'));
        for (const target of creator.project.targets) {
            for (const variable of Object.values(target.variables)) if (variable[0] === 'stored') variable[1] = value;
        }
        declined(creator.generateBASIC(undefined, options), 'variable-value');
    }
    const missing = build(pinSource('  set led to stored'));
    for (const target of missing.project.targets) target.variables = {};
    declined(missing.generateBASIC(undefined, options), 'variable-scope');
    const ambiguous = build(pinSource('  set led to stored'));
    ambiguous.project.targets.push({name: 'another sprite', blocks: {}, variables: {differentId: ['stored', 1]}});
    declined(ambiguous.generateBASIC(undefined, options), 'variable-scope');
});

test('numbered source keeps digital and delay ownership while scaffolding has no block map', () => {
    const creator = build(pinSource('  turn on led\n  wait 0.025 seconds'));
    const result = creator.generateBASIC(undefined, {...options, lineNumbers: true});
    const code = accepted(result);
    const write = blockOf(creator, 'stc12_setpin').id;
    const wait = blockOf(creator, 'control_wait').id;
    for (const line of code.trim().split('\n')) {
        assert.match(line, /^\d+ /);
        const n = Number(line.match(/^\d+/)[0]);
        if (line.includes('PROCdigitalWrite')) assert.equal(result.lineMap[n], write);
        else if (line.includes('PROCdelay')) assert.equal(result.lineMap[n], wait);
        else assert.equal(result.lineMap[n], undefined);
    }
});

